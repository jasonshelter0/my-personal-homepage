export function localizeServerMessage(message: string, locale: Locale) {
  if (locale === 'en') return message;
  const pair = serverMessages[message];
  if (pair) return pair[locale === 'zh-CN' ? 0 : 1];
  if (message.startsWith('Translation provider returned HTTP '))
    return locale === 'zh-CN'
      ? `翻译服务返回 ${message.match(/HTTP \d+/)?.[0] || 'HTTP 错误'}。`
      : `Le service de traduction a renvoyé ${message.match(/HTTP \d+/)?.[0] || 'une erreur HTTP'}.`;
  return message;
}
